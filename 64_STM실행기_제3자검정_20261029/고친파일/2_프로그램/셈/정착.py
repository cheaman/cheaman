import json, math, sys

기준 = "KDS 14 20 52 (2024-12-30)"

def _r(x, n=1):
    return round(x + 1e-9, n)

def _f(x, n=1):
    """숫자를 1,234.5 꼴로"""
    return f"{x:,.{n}f}"

# ── 4.1.2 (2) 기본정착길이 · 식 (4.1-1) ─────────────────────────────────────────
def 기본정착길이(d_b, f_y, f_ck, λ=1.0):
    """l_db = 0.6 · d_b · f_y / (λ · √f_ck)   [4.1.2(2) 식 (4.1-1)]"""
    return 0.6 * d_b * f_y / (λ * math.sqrt(f_ck))

# ── 표 4.1-1 보정계수 ────────────────────────────────────────────────────────
def 표계수(d_b, 조건, α=1.0, β=1.0):
    """
    조건1 = 순간격 d_b 이상 · 피복 d_b 이상 · 전 구간 최소 스터럽 (또는 순간격 2d_b 이상 · 피복 d_b 이상)
    기타  = 그 밖
    D19 이하(d_b ≤ 19) 와 D22 이상(d_b ≥ 22) 두 칸  [표 4.1-1]
    """
    작은 = d_b <= 19
    if 조건 == "조건1":
        k = 0.8 if 작은 else 1.0
    else:
        k = 1.2 if 작은 else 1.5
    return k * α * β, k

def 위치계수(상부철근):
    """α — 상부철근(아래 300 mm 초과 콘크리트) 1.3 · 기타 1.0  [4.1.2 ①]"""
    return 1.3 if 상부철근 else 1.0

def 도막계수(도막="없음", 피복얇음=False):
    """β — 에폭시 도막 · 피복 3d_b 미만 또는 순간격 6d_b 미만 1.5 · 기타 에폭시 1.2 · 도막 없음 1.0  [4.1.2 ②]"""
    if 도막 == "에폭시":
        return 1.5 if 피복얇음 else 1.2
    return 1.0

# ── 4.1.2 (3) 상세식 · 식 (4.1-2) ──────────────────────────────────────────────
def 정착길이_상세(d_b, f_y, f_ck, c, K_tr=0.0, λ=1.0, α=1.0, β=1.0):
    """
    l_d = [0.90 d_b f_y / (λ √f_ck)] · [α β γ / ((c + K_tr)/d_b)]   [4.1.2(3) 식 (4.1-2)]
    (c + K_tr)/d_b 는 2.5 이하 · γ = D19 이하 0.8 · D22 이상 1.0 · K_tr 은 0 으로 둘 수 있음
    돌려줌 : (l_d, γ, 쓴 (c+K_tr)/d_b)
    """
    γ = 0.8 if d_b <= 19 else 1.0
    비 = min((c + K_tr) / d_b, 2.5)
    return 0.90 * d_b * f_y / (λ * math.sqrt(f_ck)) * (α * β * γ / 비), γ, 비

def 횡방향철근지수(A_tr, s, n):
    """K_tr = 40 · A_tr / (s · n)   [4.1.2(3) ③]"""
    return 40.0 * A_tr / (s * n)

# ── 4.1.5 표준갈고리 · 식 (4.1-4) ──────────────────────────────────────────────
def 갈고리_기본정착길이(d_b, f_y, f_ck, β=1.0, λ=1.0):
    """l_hb = 0.24 · β · d_b · f_y / (λ · √f_ck)   [4.1.5(2) 식 (4.1-4)]  β 에폭시 1.2 · 도막 없음 1.0"""
    return 0.24 * β * d_b * f_y / (λ * math.sqrt(f_ck))

def 갈고리_정착길이(d_b, f_y, f_ck, β=1.0, λ=1.0, 피복보정=False, 띠철근보정=False, 소요배근=None):
    """
    l_dh = l_hb × 보정계수들 · 8 d_b 이상 · 150 mm 이상  [4.1.5(1)(3)]
    피복보정 0.7 (D35 이하 · 측면 피복 70 이상 · 90° 갈고리 넘어선 피복 50 이상) ①
    띠철근보정 0.8 (D35 이하 · 3d_b 이하 간격 띠철근) ②③ · 소요배근 = 소요 A_s / 배근 A_s ④
    돌려줌 : (l_dh, 계수 목록, 밑값 8d_b·150 에 걸렸나)
    """
    l_hb = 갈고리_기본정착길이(d_b, f_y, f_ck, β, λ)
    계수 = []
    if 피복보정 and d_b <= 35: 계수.append(("4.1.5(3)① 피복", 0.7))
    if 띠철근보정 and d_b <= 35: 계수.append(("4.1.5(3)② 띠철근 3d_b", 0.8))
    if 소요배근 is not None and 소요배근 < 1.0: 계수.append(("4.1.5(3)④ 소요/배근", 소요배근))
    값 = l_hb
    for _, k in 계수: 값 *= k
    밑 = max(8 * d_b, 150.0)
    return max(값, 밑), 계수, 값 < 밑, l_hb

# ── 검토 한 벌 (타이 하나) ────────────────────────────────────────────────────
def 검토(d_b, f_y, f_ck, l_anc, 꼴="직선", 조건="조건1", 상부철근=False, 도막="없음", 피복얇음=False,
        λ=1.0, 소요배근=None, 피복보정=False, 띠철근보정=False, 방법="간략", c=None, K_tr=0.0):
    """
    l_anc = 절점에서 쓸 수 있는 정착 길이 (연장 가능 길이 · mm)
    꼴 = "직선" | "갈고리90" | "갈고리180" · 방법 = "간략"(표 4.1-1) | "상세"(식 4.1-2 · c 필요)
    돌려줌 dict : 필요 · 있는(l_anc) · 비 · 판정 · 식줄[] · 고칠길(직선 NG 면 갈고리 90° 로 다시 센 dict)
    """
    if 꼴 not in ("직선", "갈고리90", "갈고리180"):
        raise ValueError(f"정착 형태 «{꼴}» 은 지원하지 않음 — 직선 · 갈고리90 · 갈고리180 가운데 선택")   # 10-29 검정 : 전엔 모르는 꼴이 갈고리로 셈
    α = 위치계수(상부철근); β = 도막계수(도막, 피복얇음)
    줄 = []
    if 꼴 == "직선":
        if 방법 == "상세":
            if c is None: raise ValueError("상세식은 c (철근 중심~표면 최단거리 또는 중심간 거리/2) 가 필요")
            l, γ, 비 = 정착길이_상세(d_b, f_y, f_ck, c, K_tr, λ, α, β)
            줄.append(f"l_d = 0.90·d_b·f_y/(λ√f_ck) · αβγ/((c+K_tr)/d_b) = 0.90×{d_b}×{f_y}/({λ}×√{f_ck}) × {α}×{β}×{γ}/{_f(비,2)} = {_f(l)} mm  [{기준} 4.1.2(3) 식 (4.1-2)]")
            if (c + K_tr) / d_b > 2.5: 줄.append(f"  (c+K_tr)/d_b = {_f((c+K_tr)/d_b,2)} > 2.5 → 2.5 로 둠  [4.1.2(3)]")
        else:
            l_db = 기본정착길이(d_b, f_y, f_ck, λ)
            k, k0 = 표계수(d_b, 조건, α, β)
            l = l_db * k
            줄.append(f"l_db = 0.6·d_b·f_y/(λ√f_ck) = 0.6×{d_b}×{f_y}/({λ}×√{f_ck}) = {_f(l_db)} mm  [{기준} 4.1.2(2) 식 (4.1-1)]")
            줄.append(f"보정계수 = {k0}·α·β = {k0}×{α}×{β} = {_f(k,2)}  ({'D19 이하' if d_b<=19 else 'D22 이상'} · {조건})  [표 4.1-1]")
            줄.append(f"l_d = {_f(l_db)} × {_f(k,2)} = {_f(l)} mm")
        if 소요배근 is not None and 소요배근 < 1.0:
            l *= 소요배근; 줄.append(f"×(소요 A_s/배근 A_s) = ×{_f(소요배근,3)} → {_f(l)} mm  [4.1.2(4)]")
        if l < 300:
            줄.append(f"{_f(l)} < 300 → l_d = 300 mm  [4.1.2(1)]"); l = 300.0
        필요 = l; 이름 = "l_d"
    else:
        β = 1.2 if 도막 == "에폭시" else 1.0     # 갈고리 β 는 도막 유무만 (에폭시 1.2 · 없음 1.0) [4.1.5(2)] — 10-29 검정 : 전엔 직선용 1.5 (얇은 피복) 가 그대로 들어감
        l, 계수, 밑걸림, l_hb = 갈고리_정착길이(d_b, f_y, f_ck, β, λ, 피복보정, 띠철근보정, 소요배근)
        줄.append(f"l_hb = 0.24·β·d_b·f_y/(λ√f_ck) = 0.24×{β}×{d_b}×{f_y}/({λ}×√{f_ck}) = {_f(l_hb)} mm  [{기준} 4.1.5(2) 식 (4.1-4)]")
        for 이, k in 계수: 줄.append(f"×{k} ({이})")
        if 밑걸림: 줄.append(f"8d_b = {8*d_b} · 150 mm 밑값에 걸림 → l_dh = {_f(l)} mm  [4.1.5(1)]")
        else: 줄.append(f"l_dh = {_f(l)} mm  ({'갈고리 90°' if 꼴=='갈고리90' else '갈고리 180°'})")
        필요 = l; 이름 = "l_dh"
    비 = l_anc / 필요 if 필요 else float("inf")
    판정 = "O.K" if l_anc >= 필요 - 1e-9 else "N.G"
    줄.append(f"{이름} = {_f(필요)} mm {'≤' if 판정=='O.K' else '>'} l_anc = {_f(l_anc)} mm → 검토비 {_f(비,2)} ∴ {판정}")
    r = {"꼴": 꼴, "이름": 이름, "필요": _r(필요), "있는": l_anc, "비": _r(비, 3), "판정": 판정, "α": α, "β": β, "식줄": 줄}
    if 판정 == "N.G" and 꼴 == "직선":
        r["고칠길"] = 검토(d_b, f_y, f_ck, l_anc, "갈고리90", 조건, 상부철근, 도막, 피복얇음, λ, 소요배근, 피복보정, 띠철근보정)
    return r

# ── 정답지 대조 (모두대조.py 가 «대조 … ✔» 줄을 센다) ──────────────────────────
def 대조(경로):
    d = json.load(open(경로, encoding="utf-8"))
    print(f"== {d['이름']} — {d.get('출처','')}")
    for 건 in d["건"]:
        r = 검토(**건["입력"])
        for 열쇠, 정답 in 건["기대"].items():
            얻 = r[열쇠] if 열쇠 in r else r["고칠길"][열쇠.replace("고칠길.", "")]
            if isinstance(정답, (int, float)):
                차 = abs(얻 - 정답) / abs(정답) * 100 if 정답 else abs(얻 - 정답)
                ok = 차 <= 건.get("허용%", 0.1)
                print(f"  대조 {건['이름']:14s} {열쇠:8s} 얻 {얻:>10.1f} · 정답 {정답:>10.1f} · 차 {차:.2f} % {'✔' if ok else '✘'}")
            else:
                ok = 얻 == 정답
                print(f"  대조 {건['이름']:14s} {열쇠:8s} 얻 {얻!s:>10s} · 정답 {정답!s:>10s} {'✔' if ok else '✘'}")

