# ── 판요소 국부축 규칙 (2026-10-15 · 부서원 음성 의견 · 1_기록 172) ─────────────
#   슬래브 : 국부 x = 글로벌 +X · y = +Y · z = +Z (위)          → Mxx = X 방향 휨 (X 방향 철근)
#   벽     : 국부 z = 안쪽 · y = 위 (+Z) · x = y × z (안에서 벽을 보면 오른쪽 가로) → Mxx = 가로 휨 (수평 철근)
#            바깥벽의 «안쪽» = 토압과 같은 셈 (하중계산.안쪽부호) · 양쪽이 다 안인 격벽 = 구조물 가운데 쪽 (전무님 10-15)
#   ★ 요소 줄 끝 «3, −90» 은 그대로 둡니다 — −90 은 «절점 1→2 를 z 둘레 −90° 돌린 것이 국부 x» (기록 28 · 결과로 확인한 뜻)
#     그래서 1→2 를 «바라는 y» 로, 면 법선 (1→2)×(1→끝) 을 «바라는 z» 로 오게 절점 차례만 돌립니다 (MIDAS 새 뜻을 지어내지 않음)
#   ★ 절점마다 다른 면하중 (HYDRO P1 ~ P4) 도 같은 차례로 따라 돌립니다 — 값이 절점 차례대로 들어 있음 (하중계산 절점마다)

def _벡뺄(a, b):
    return [a[0] - b[0], a[1] - b[1], a[2] - b[2]]


def _벡곱(a, b):
    return [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]]


def _벡단(v):
    L = (v[0] ** 2 + v[1] ** 2 + v[2] ** 2) ** 0.5
    return [x / L for x in v] if L > 1e-12 else None


def _벡점(a, b):
    return a[0] * b[0] + a[1] * b[1] + a[2] * b[2]


