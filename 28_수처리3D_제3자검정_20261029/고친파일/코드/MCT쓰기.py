def _조합이름(이름):
    """'Case 01' → 'Case1' · 'SCase 07' → 'SCase7' · 'SusCase 02' → 'SusCase2' (정답지 이름 꼴)"""
    import re
    m = re.match(r'([A-Za-z]+)\s*0*(\d+)', 이름)
    return (m.group(1) + m.group(2)) if m else 이름.replace(' ', '')


