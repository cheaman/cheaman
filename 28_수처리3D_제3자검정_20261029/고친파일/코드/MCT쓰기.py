def _면넓이(ps):
    """3D 다각형 넓이 — 벡터곱 합의 절반 (벽처럼 선 판도 제 넓이 그대로)"""
    sx = sy = sz = 0.0
    for i in range(len(ps)):
        a, b = ps[i], ps[(i + 1) % len(ps)]
        sx += a[1] * b[2] - a[2] * b[1]
        sy += a[2] * b[0] - a[0] * b[2]
        sz += a[0] * b[1] - a[1] * b[0]
    return 0.5 * (sx * sx + sy * sy + sz * sz) ** 0.5


