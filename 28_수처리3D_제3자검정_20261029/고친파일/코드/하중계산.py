def 위법선(점, 판):
    """판요소 면의 단위 법선 — 위(+Z)를 보게 뒤집어 (nx, ny, nz) · 못 셈이면 None (★ 10-06 경사판 수평 하중 · 1_기록 121)"""
    P = [(float(점[b]['X']), float(점[b]['Y']), float(점[b]['Z']))
         for b in [int(v) for v in (판.get('절점') or [])] if b and b in 점]
    if len(P) < 3:
        return None
    a = [P[1][i] - P[0][i] for i in range(3)]
    c = [P[-1][i] - P[0][i] for i in range(3)]
    n = [a[1] * c[2] - a[2] * c[1], a[2] * c[0] - a[0] * c[2], a[0] * c[1] - a[1] * c[0]]
    L = math.sqrt(sum(v * v for v in n))
    if L < 1e-12:
        return None
    n = [v / L for v in n]
    return tuple(-v for v in n) if n[2] < 0 else tuple(n)


