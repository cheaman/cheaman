    # ★ 10-26 밤 (1_기록 191 · 지휘 «계산서 식으로 맞춤») 식틀 '계산서' = 표준 계산서 (스크린실) 7.5 그대로
    #   U(z) = 2/π² · Sv · TS · cos(πz/2H) · TS = 1.25·TG (O152) · 기준 = 저판 «하면» 깊이 zB (O167) · z > H 면 0
