def _칸찾기(지도들, x, y, z):
    for 층 in 지도들:
        z0, z1, 젖음, xmin, ymin, 열, 행, 눈금, 벽칸 = 층
        if z0 < z < z1 or abs(z - z0) < 1e-6 or abs(z - z1) < 1e-6:
            i, j = int((x - xmin) / 눈금), int((y - ymin) / 눈금)
            return 층, i, j
    return None, 0, 0


def 젖었나(지도들, x, y, z):
    """그 자리가 바깥(젖은 칸)인가 — 층을 못 찾으면 None · 벽 칸 위면 None · 격자 밖이면 True"""
    층, i, j = _칸찾기(지도들, x, y, z)
    if 층 is None:
        return None
    _, _, 젖음, _, _, 열, 행, _, 벽칸 = 층
    if not (0 <= i < 열 and 0 <= j < 행):
        return True
    if 벽칸[j][i]:
        return None
    return 젖음[j][i]


def 안쪽인가(지도들, x, y, z):
    """슬래브 자리가 건물 안인가 — 벽 칸 위(벽 두께 아래)면 이웃 넷 중 «마른 빈 칸» 이 있어야 안쪽. 층을 못 찾으면 None"""
    층, i, j = _칸찾기(지도들, x, y, z)
    if 층 is None:
        return None
    _, _, 젖음, _, _, 열, 행, _, 벽칸 = 층
    if not (0 <= i < 열 and 0 <= j < 행):
        return False
    if not 벽칸[j][i]:
        return not 젖음[j][i]
    for a, b in ((i + 1, j), (i - 1, j), (i, j + 1), (i, j - 1)):
        if 0 <= a < 열 and 0 <= b < 행 and not 벽칸[b][a] and not 젖음[b][a]:
            return True
    return False


