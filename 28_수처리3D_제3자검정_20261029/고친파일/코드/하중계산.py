def 보정계수(h):
    """상재흙하중 보정계수 αH  (계산서 6.2)

        h > 2.0 m  →  αH = 1.05 - 0.025 × h   (≥ 0.875)
        h ≤ 2.0 m  →  αH = 1.0

    ★ 09-30 — 하한 0.875 는 계산서 6.2 W48 (IF(αH ≥ 0.875, αH, 0.875)) 그대로입니다.
      전에는 0 까지 내려가 h 가 7 m 를 넘으면 계산서보다 작게 셈했습니다 (1_기록 40)
      화면\지반지진셈.js 의 보정αH 와 같아야 합니다 (셈 과정 표 ⑬)
    """
    if h is None:
        return 1.0
    if h <= 2.0:
        return 1.0
    return max(0.875, 1.05 - 0.025 * h)


def 상재흙하중(설계값, 지하수있나):
    """상부슬래브 위 흙무게 (kN/m²) — 계산서 6.2

        지하수 없을 때 : PL = γ × h
        지하수 있을 때 : PL = γ × h1 + γsub × h2   (h2 = 지하수 아래 몫)
        적용하중        : αH × PL
    """
    h = float(설계값.get('토피') or 0)
    if h <= 0:
        return 0.0
    γ = float(설계값.get('흙단위중량') or 19)
    if not 지하수있나:
        PL = γ * h
    else:
        γs = float(설계값.get('흙수중단위중량') or 10)
        # 지하수위가 흙 속 어디인지 — 토피 안에서만 봅니다
        아래 = min(h, max(0.0, float(설계값.get('지하수깊이') or 0)))
        PL = γ * (h - 아래) + γs * 아래
    # ★ 10-08 표준 틀 (스크린실 계산서 9.1.2) — αH 는 하중 «계수» 1.6αH 로 (MCT쓰기.표준조합) · 하중 값은 PL 그대로
    #   옛 틀 (빗물 · 유입분배조 계산서 6.2) — 값에 αH 를 곱함 (지난 결과 대조가 안 깨지게 그대로)
    if (설계값.get('조합틀') or '표준') != '옛틀':
        return round(PL, 3)
    return round(보정계수(설계값.get('aH계산h')) * PL, 3)


def 횡토압qw(설계값):
    """횡토압에 더하는 상재하중 qw (kN/m²) — 횡토압 · 하중근거 가 같은 값을 쓰게 한 곳에"""
    # ★ 10-08 표준 (스크린실 계산서 6.3.1 O112) — 차량 통행 있음이면 상재하중 q = 노면 활하중 PL (화면 활하중 칸 값)
    if 설계값.get('차량통행') and (설계값.get('조합틀') or '표준') != '옛틀':
        return float(설계값.get('활하중') or 0)
    return float(설계값.get('상재하중qw') or 0)


def 횡토압(설계값, 깊이, 지하수있나, 물깊이=0.0):
    """그 깊이에서 벽에 걸리는 수평 토압 (kN/m²) — 계산서 6.4

        P = Ko × (qw + γ × 흙깊이)
        지하수 아래 흙은 수중단위중량을 씁니다
    """
    Ko = float(설계값.get('Ko') or 0.5)
    qw = 횡토압qw(설계값)
    γ = float(설계값.get('흙단위중량') or 19)
    γs = float(설계값.get('흙수중단위중량') or 10)
    if not 지하수있나 or 물깊이 <= 0:
        흙 = γ * 깊이
    else:
        마른 = max(0.0, 깊이 - 물깊이)
        흙 = γ * 마른 + γs * min(깊이, 물깊이)
    return round(Ko * (qw + 흙), 3)


def 활하중합(설계값):
    """활하중 케이스에 드는 값 (kN/m²) 과 근거 한 줄 — 2026-10-06 저녁 전무님 정함 (1_기록 128)

        값  = 활하중 (군중 = 입력값 · 차도 밑 = 화면이 토피로 표에서 읽은 값)
            + qw   (화면 «qw 를 상부슬래브에도 연직으로» 를 켰을 때만 · 기본 끔)
    """
    활 = float(설계값.get('활하중') or 0)
    근거 = str(설계값.get('활하중근거') or '').strip() or ('입력값 %g' % 활)
    if 설계값.get('상재하중연직'):
        qw = float(설계값.get('상재하중qw') or 0)
        if qw and '+ qw' not in 근거:
            근거 += ' + qw %g = %g kN/m²' % (qw, 활 + qw)
        활 += qw
    return round(활, 3), 근거


def 수압(설계값, 물깊이):
    """지하수압 · 내부수압 · 양압력 (kN/m²) — 계산서 6.5·6.6·6.7

        P = γw × 깊이      (물 위쪽은 0)
    """
    if 물깊이 <= 0:
        return 0.0
    return round(float(설계값.get('물단위중량') or 10) * 물깊이, 3)


