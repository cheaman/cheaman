def 슬래브EL고르기(높이들, 넣은EL, 자리=None, 구역=None):
    """넣은 EL 에 가장 가까운 슬래브 높이 · 돌려주는 것 (EL, 알림 또는 None)

    EL 이 비면 — ★ 10-01 실측으로 «맨 위 슬래브» 를 버림 (빗물 맨 위 EL 21.15 는 한쪽 일부뿐이라 반력이 15 m 떨어진 절점에 붙음)
      점  (자리 = (x, y))           : 그 평면 자리를 덮는 슬래브 가운데 가장 높은 것 (그 자리의 지붕)
      구역 (구역 = (x0, x1, y0, y1)) : 구역 안에 판 가운데가 드는 슬래브 가운데 가장 높은 것
      덮는 슬래브가 없으면 맨 위 + 알림
    """
    if not 높이들:
        return None, '슬래브가 없음'
    if 넣은EL is None or 넣은EL == '':
        for EL in sorted(높이들, reverse=True):
            for (a, b, c, d, cx, cy) in 높이들[EL].get('상자') or []:
                if 자리 is not None and a - 1e-6 <= 자리[0] <= b + 1e-6 and c - 1e-6 <= 자리[1] <= d + 1e-6:
                    return EL, None
                if 구역 is not None and 구역[0] - 1e-6 <= cx <= 구역[1] + 1e-6 and 구역[2] - 1e-6 <= cy <= 구역[3] + 1e-6:
                    return EL, None
        return max(높이들), ('그 자리를 덮는 슬래브가 없음 → 맨 위 EL %g 에' % max(높이들)) if (자리 or 구역) else None
    try:
        e = float(넣은EL)
    except (TypeError, ValueError):
        return max(높이들), '넣은 EL «%s» 를 못 읽음 → 맨 위 슬래브' % 넣은EL
    가장 = min(높이들, key=lambda k: abs(k - e))
    if abs(가장 - e) > 0.1:
        return 가장, '넣은 EL %g 에 슬래브 없음 → 가장 가까운 EL %g 에' % (e, 가장)
    return 가장, None


def 판넓이(그물, 판, 점=None):
    """판요소 넓이 (m²) — 네 절점이면 두 대각선 외적의 절반 · 셋이면 세모"""
    if 점 is None:
        점 = {int(n['번']): n for n in 그물.get('절점', [])}
    ps = [(float(점[int(b)]['X']), float(점[int(b)]['Y']), float(점[int(b)]['Z'])) for b in (판.get('절점') or []) if int(b) in 점]
    if len(ps) < 3:
        return 0.0
    if len(ps) >= 4:
        a = [ps[2][i] - ps[0][i] for i in range(3)]
        b = [ps[3][i] - ps[1][i] for i in range(3)]
    else:
        a = [ps[1][i] - ps[0][i] for i in range(3)]
        b = [ps[2][i] - ps[0][i] for i in range(3)]
    x = [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]]
    return 0.5 * math.sqrt(sum(v * v for v in x))


def _꼴넓이(꼴):
    """꼭짓점 [(x, y) …] 의 넓이 (신발끈 셈) — 기계하중읽기.꼴넓이 와 같은 셈 (요청마다 새로 읽히게 여기에 둠)"""
    n = len(꼴)
    return abs(0.5 * sum(꼴[i][0] * 꼴[(i + 1) % n][1] - 꼴[(i + 1) % n][0] * 꼴[i][1] for i in range(n)))


def _꼴안(x, y, 꼴):
    """점이 꼴 안인가 (반직선 세기) — 기계하중읽기.안에있나 와 같은 셈"""
    안 = False
    n = len(꼴)
    for i in range(n):
        (x1, y1), (x2, y2) = 꼴[i], 꼴[(i + 1) % n]
        if (y1 > y) != (y2 > y) and x < x1 + (y - y1) * (x2 - x1) / (y2 - y1):
            안 = not 안
    return 안


